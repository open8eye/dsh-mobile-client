  /// Look up [key], falling back to English and finally to the key itself so a
  /// missing string is visible in the UI instead of crashing.
  String t(String key) {
    final table = _table[code] ?? _table['en']!;
    return table[key] ?? _table['en']![key] ?? key;
  }

  /// Whether [code] has a translation table.
  static bool supports(String code) => _table.containsKey(code);

  static const List<String> supportedCodes = <String>['zh', 'en'];
}

/// Exposes the active [L10n] to the widget tree.
class L10nScope extends InheritedWidget {
  const L10nScope({required this.l10n, required super.child, super.key});

  final L10n l10n;

  static L10n of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<L10nScope>();
    assert(scope != null, 'L10nScope is missing from the widget tree');
    return scope!.l10n;
  }

  @override
  bool updateShouldNotify(L10nScope oldWidget) => oldWidget.l10n.code != l10n.code;
}

/// Shorthand used throughout the UI: `context.tr('settingsTitle')`.
extension L10nContext on BuildContext {
  String tr(String key) => L10nScope.of(this).t(key);
}
